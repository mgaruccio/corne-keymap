#!/usr/bin/env python3
"""Generate the Corne keymap and telemetry constants from the viewer's layout."""

import argparse
import json
from pathlib import Path
import re
import sys
from uuid import UUID

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "configs" / "corne"
BINDING = re.compile(r"&[a-z][a-z0-9_]*(?: (?:[A-Z][A-Z0-9_]*(?:\([A-Z][A-Z0-9_]*\))?|[0-9]+))*")
PREAMBLE = """/* Generated by scripts/generate-corne-keymap.py; edit layout.json instead. */
#include <behaviors.dtsi>
#include <dt-bindings/zmk/keys.h>
#include <dt-bindings/zmk/bt.h>

/ {
    chosen {
        zmk,physical-layout = &foostan_corne_6col_layout;
    };

    behaviors {
        outside_mod: outside_mod {
            compatible = "zmk,behavior-hold-tap";
            #binding-cells = <2>;
            flavor = "hold-preferred";
            tapping-term-ms = <200>;
            quick-tap-ms = <200>;
            bindings = <&kp>, <&kp>;
            display-name = "Outside Mod-Tap";
        };
        space_cadet: space_cadet {
            compatible = "zmk,behavior-hold-tap";
            #binding-cells = <2>;
            flavor = "hold-preferred";
            tapping-term-ms = <200>;
            quick-tap-ms = <0>;
            bindings = <&kp>, <&kp>;
            display-name = "Space Cadet";
        };
        thumb_lt: thumb_layer_tap {
            compatible = "zmk,behavior-hold-tap";
            #binding-cells = <2>;
            flavor = "balanced";
            tapping-term-ms = <200>;
            quick-tap-ms = <200>;
            bindings = <&mo>, <&kp>;
            display-name = "Thumb Layer-Tap";
        };
        esc_lt: escape_layer_tap {
            compatible = "zmk,behavior-hold-tap";
            #binding-cells = <2>;
            flavor = "hold-preferred";
            tapping-term-ms = <200>;
            quick-tap-ms = <0>;
            bindings = <&mo>, <&kp>;
            display-name = "Escape Layer-Tap";
        };
    };

    keymap {
        compatible = "zmk,keymap";
"""


def validate(layout):
    for field in ("service_uuid", "characteristic_uuid"):
        if str(UUID(layout[field])) != layout[field]:
            raise ValueError(f"{field} must be a canonical UUID")
    layers = layout["layers"]
    if len(layers) != 3:
        raise ValueError("the firmware requires exactly three layers")
    for layer in layers:
        if not isinstance(layer["name"], str) or not layer["name"].isascii():
            raise ValueError("layer names must be ASCII strings")
        if len(layer["keys"]) != 42:
            raise ValueError(f"{layer['name']}: expected 42 keys in interleaved row order")
        for key in layer["keys"]:
            if any(not isinstance(key[field], str) for field in ("tap", "hold", "repeat", "binding")):
                raise ValueError("tap, hold, repeat and binding must be strings")
            if not BINDING.fullmatch(key["binding"]):
                raise ValueError(f"invalid DTS binding: {key['binding']!r}")
            if key["binding"] == "&trans" and (key["tap"], key["hold"], key["repeat"]) != ("↳", "", ""):
                raise ValueError("transparent keys must have tap=↳ and empty hold/repeat")


def render_keymap(layout):
    lines = [PREAMBLE.rstrip()]
    for index, layer in enumerate(layout["layers"]):
        lines.extend([
            f"        layer_{index} {{",
            f"            display-name = {json.dumps(layer['name'])};",
            "            bindings = <",
        ])
        keys = [key["binding"] for key in layer["keys"]]
        # Three interleaved 6+6 rows, then left three + right three thumbs.
        for start, half in ((0, 6), (12, 6), (24, 6), (36, 3)):
            left = "  ".join(keys[start:start + half])
            right = "  ".join(keys[start + half:start + 2 * half])
            lines.append(f"                {left}    {right}")
        lines.extend(["            >;", "        };"])
    lines.extend(["    };", "};", ""])
    return "\n".join(lines)


def render_header(layout):
    def encoded(field):
        return "BT_UUID_128_ENCODE(" + ", ".join("0x" + part for part in layout[field].split("-")) + ")"

    return (
        "/* Generated by scripts/generate-corne-keymap.py; edit layout.json instead. */\n"
        "#pragma once\n\n"
        f"#define CORNE_LAYER_COUNT {len(layout['layers'])}\n"
        f"#define CORNE_SERVICE_UUID {encoded('service_uuid')}\n"
        f"#define CORNE_LAYER_UUID {encoded('characteristic_uuid')}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    try:
        layout = json.loads((CONFIG / "layout.json").read_text(encoding="utf-8"))
        validate(layout)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.error(str(exc))
    outputs = {
        CONFIG / "blecorne.keymap": render_keymap(layout),
        CONFIG / "telemetry" / "include" / "corne_layout.h": render_header(layout),
    }
    stale = False
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"Stale: {path.relative_to(ROOT)}; run {Path(__file__).name}", file=sys.stderr)
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(path.relative_to(ROOT))
    return int(stale)


if __name__ == "__main__":
    raise SystemExit(main())
